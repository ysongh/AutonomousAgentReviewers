#!/usr/bin/env node
// Generates 4 fresh wallets (one per agent) and writes them to .env.agents
// at the project root. Prints the addresses and stops — the user funds them
// manually from https://faucet.0g.ai before continuing.
//
// Usage:
//   node scripts/generate-agent-wallets.js          # refuses if .env.agents exists
//   node scripts/generate-agent-wallets.js --force  # overwrite existing file

const fs = require('fs');
const path = require('path');
const { ethers } = require(path.join(__dirname, '..', 'shared', 'node_modules', 'ethers'));

const ROOT = path.resolve(__dirname, '..');
const ENV_AGENTS_PATH = path.join(ROOT, '.env.agents');
const GITIGNORE_PATH = path.join(ROOT, '.gitignore');

const AGENTS = [
  { id: 'intake',            prefix: 'INTAKE' },
  { id: 'judge-technical',   prefix: 'JUDGE_TECHNICAL' },
  { id: 'judge-originality', prefix: 'JUDGE_ORIGINALITY' },
  { id: 'judge-skeptic',     prefix: 'JUDGE_SKEPTIC' },
];

function ensureGitignored() {
  let contents = '';
  if (fs.existsSync(GITIGNORE_PATH)) {
    contents = fs.readFileSync(GITIGNORE_PATH, 'utf8');
  }
  const lines = contents.split('\n').map((l) => l.trim());
  if (lines.includes('.env.agents')) return false;
  const updated = (contents.endsWith('\n') || contents === '' ? contents : contents + '\n') + '.env.agents\n';
  fs.writeFileSync(GITIGNORE_PATH, updated);
  return true;
}

function main() {
  const force = process.argv.includes('--force');
  if (fs.existsSync(ENV_AGENTS_PATH) && !force) {
    console.error('.env.agents already exists at', ENV_AGENTS_PATH);
    console.error('Refusing to overwrite. Re-run with --force to regenerate (this will invalidate the existing wallets).');
    process.exit(1);
  }

  const lines = ['# Per-agent wallets for 0G Galileo testnet — see CLAUDE.md.', '# Generated by scripts/generate-agent-wallets.js. Do not commit.', ''];
  const rows = [];
  for (const { id, prefix } of AGENTS) {
    const w = ethers.Wallet.createRandom();
    lines.push(`${prefix}_PRIVATE_KEY=${w.privateKey}`);
    lines.push(`${prefix}_ADDRESS=${w.address}`);
    lines.push('');
    rows.push({ id, address: w.address });
  }

  fs.writeFileSync(ENV_AGENTS_PATH, lines.join('\n'), { mode: 0o600 });
  const addedToGitignore = ensureGitignored();

  console.log('Wrote', ENV_AGENTS_PATH, '(mode 0600)');
  if (addedToGitignore) console.log('Added .env.agents to .gitignore');
  console.log();
  console.log('Agent addresses:');
  console.log('  Agent              Address');
  console.log('  -----------------  ------------------------------------------');
  for (const r of rows) {
    console.log('  ' + r.id.padEnd(17) + '  ' + r.address);
  }
  console.log();
  console.log('Fund each address with 0.05 0G from https://faucet.0g.ai before proceeding to step 2.');
  console.log('When all four are funded, run: node scripts/check-agent-balances.js');
}

main();
