#!/usr/bin/env node
// Generates fresh wallets (one per agent) and writes them to .env.agents at
// the project root. Prints the addresses and stops — the user funds them
// manually from https://faucet.0g.ai before continuing.
//
// Behavior:
//   - .env.agents missing               → generate all agents, write fresh file
//   - .env.agents exists, missing some  → APPEND only the missing agents
//                                          (preserves existing funded wallets)
//   - .env.agents exists, all present   → refuse unless --force
//   - --force                           → regenerate ALL agents (invalidates
//                                          existing funded wallets)
//
// Usage:
//   node scripts/generate-agent-wallets.js
//   node scripts/generate-agent-wallets.js --force

const fs = require('fs');
const path = require('path');
const { ethers } = require(path.join(__dirname, '..', 'shared', 'node_modules', 'ethers'));

const ROOT = path.resolve(__dirname, '..');
const ENV_AGENTS_PATH = path.join(ROOT, '.env.agents');
const GITIGNORE_PATH = path.join(ROOT, '.gitignore');

const AGENTS = [
  { id: 'intake',            prefix: 'INTAKE' },
  { id: 'judge-technical',   prefix: 'JUDGE_TECHNICAL' },
  { id: 'judge-originality', prefix: 'JUDGE_ORIGINALITY' },
  { id: 'judge-skeptic',     prefix: 'JUDGE_SKEPTIC' },
  { id: 'aggregator',        prefix: 'AGGREGATOR' },
];

function ensureGitignored() {
  let contents = '';
  if (fs.existsSync(GITIGNORE_PATH)) {
    contents = fs.readFileSync(GITIGNORE_PATH, 'utf8');
  }
  const lines = contents.split('\n').map((l) => l.trim());
  if (lines.includes('.env.agents')) return false;
  const updated = (contents.endsWith('\n') || contents === '' ? contents : contents + '\n') + '.env.agents\n';
  fs.writeFileSync(GITIGNORE_PATH, updated);
  return true;
}

function parseExistingPrefixes(contents) {
  const present = new Set();
  for (const line of contents.split('\n')) {
    const m = line.match(/^([A-Z_]+)_PRIVATE_KEY=/);
    if (m) present.add(m[1]);
  }
  return present;
}

function main() {
  const force = process.argv.includes('--force');
  const exists = fs.existsSync(ENV_AGENTS_PATH);

  let toGenerate;
  let mode; // 'create' | 'append' | 'force'
  let existingContents = '';

  if (force) {
    toGenerate = AGENTS;
    mode = 'force';
  } else if (!exists) {
    toGenerate = AGENTS;
    mode = 'create';
  } else {
    existingContents = fs.readFileSync(ENV_AGENTS_PATH, 'utf8');
    const present = parseExistingPrefixes(existingContents);
    toGenerate = AGENTS.filter((a) => !present.has(a.prefix));
    if (toGenerate.length === 0) {
      console.error('.env.agents already contains all', AGENTS.length, 'agent wallets at', ENV_AGENTS_PATH);
      console.error('Nothing to do. Re-run with --force to regenerate (this will invalidate the existing wallets).');
      process.exit(1);
    }
    mode = 'append';
  }

  const newRows = [];
  const newLines = [];
  for (const { id, prefix } of toGenerate) {
    const w = ethers.Wallet.createRandom();
    newLines.push(`${prefix}_PRIVATE_KEY=${w.privateKey}`);
    newLines.push(`${prefix}_ADDRESS=${w.address}`);
    newLines.push('');
    newRows.push({ id, address: w.address });
  }

  if (mode === 'append') {
    const sep = existingContents.endsWith('\n') ? '' : '\n';
    const appended =
      existingContents +
      sep +
      `# Appended by scripts/generate-agent-wallets.js on ${new Date().toISOString()}\n` +
      newLines.join('\n');
    fs.writeFileSync(ENV_AGENTS_PATH, appended, { mode: 0o600 });
  } else {
    const header = [
      '# Per-agent wallets for 0G Galileo testnet — see CLAUDE.md.',
      '# Generated by scripts/generate-agent-wallets.js. Do not commit.',
      '',
    ];
    fs.writeFileSync(ENV_AGENTS_PATH, header.concat(newLines).join('\n'), { mode: 0o600 });
  }
  const addedToGitignore = ensureGitignored();

  if (mode === 'append') {
    console.log('Appended', toGenerate.length, 'new wallet(s) to', ENV_AGENTS_PATH);
  } else {
    console.log('Wrote', ENV_AGENTS_PATH, '(mode 0600)');
  }
  if (addedToGitignore) console.log('Added .env.agents to .gitignore');
  console.log();
  console.log('New agent addresses:');
  console.log('  Agent              Address');
  console.log('  -----------------  ------------------------------------------');
  for (const r of newRows) {
    console.log('  ' + r.id.padEnd(17) + '  ' + r.address);
  }
  console.log();
  console.log('Fund each NEW address with 0.05 0G from https://faucet.0g.ai before proceeding.');
  console.log('When funded, run: node scripts/check-agent-balances.js');
}

main();
